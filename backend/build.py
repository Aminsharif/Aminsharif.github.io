"""Static article generator.

Turns database articles into real ``<slug>.html`` pages at the project root, so
every insight is served as plain, crawlable HTML instead of being rendered by
JavaScript from ``/article.html?slug=…``.

How it stays in sync with the rest of the site
----------------------------------------------
The page chrome — ``<head>`` asset links, the header navigation and the footer —
is lifted verbatim from a reference page, so it can never drift:

    CHROME_SOURCE = "n8n-error-handling-monitoring.html"

Only the ``<head>`` metadata / JSON-LD and the ``<main>`` region are generated
(``backend/templates/public/insight_article.html``).

Which files it is allowed to touch
----------------------------------
Generated files start with ``GENERATED_MARKER``. Hand-written article pages are
never overwritten, and only marked files are ever deleted or rewritten.

Usage (from the project root):

    python -m backend.build          # write pages, sitemap and the noscript list
    python -m backend.build --check  # exit 1 if anything on disk is out of date
"""

