# ---------------------------------------------------------------------------
#  Helpers
# ---------------------------------------------------------------------------
def _attr(value) -> str:
    return html.escape(str(value or ""), quote=True)


def _text(value) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _iso_day(value) -> str:
    if isinstance(value, datetime):
        return value.date().isoformat()
    if isinstance(value, date):
        return value.isoformat()
    return _text(value)


def _pretty_day(value) -> str:
    if isinstance(value, (datetime, date)):
        return f"{value.strftime('%b')} {value.day}, {value.year}"
    return ""


def _abs(path_or_url: str) -> str:
    if not path_or_url:
        return SITE_URL + DEFAULT_OG_IMAGE
    if path_or_url.startswith(("http://", "https://")):
        return path_or_url
    return SITE_URL + "/" + path_or_url.lstrip("/")


def _slugify(text: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", _text(text).lower())
    return text.strip("-")


def _line_start(text: str, index: int) -> int:
    return text.rfind("\n", 0, index) + 1


def article_href(article: dict) -> str:
    """Where an article lives: its static file if it has one."""
    return article.get("external_url") or f"{article['slug']}.html"


def is_generated(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        return path.read_text(encoding="utf-8", errors="replace").lstrip().startswith(
            GENERATED_MARKER
        )
    except OSError:
        return False


def build_target(article: dict) -> str | None:
    """The static file this article owns, or ``None`` if it is served elsewhere.

    A page that exists *without* ``GENERATED_MARKER`` belongs to a human and is
    never claimed — not even when the article's slug matches its file name.
    That is what keeps the hand-written articles safe, including if someone
    clears the article's External URL.
    """
    ext = (article.get("external_url") or "").strip()
    if ext.startswith(("http://", "https://")):
        return None  # hosted on another site

    default = f"{article['slug']}.html"
    target = ext or default
    path = ROOT_DIR / target

    if path.is_file() and not is_generated(path):
        return None  # a hand-written page: leave it alone
    if ext and ext != default:
        return None  # points at a name this build does not own
    return target  # ours (marked), or our default name after a delete


# ---------------------------------------------------------------------------
#  Data
# ---------------------------------------------------------------------------
def load_articles() -> list[dict]:
    rows = query_all(
        """
        SELECT a.id, a.title, a.slug, a.excerpt, a.content, a.read_time, a.status,
               a.external_url, a.meta_title, a.meta_description, a.cover_image,
               a.published_at, a.updated_at,
               c.name AS category_name, c.slug AS category_slug
        FROM articles a
        LEFT JOIN categories c ON c.id = a.category_id
        WHERE a.status = 'published'
        ORDER BY a.published_at DESC NULLS LAST, a.id DESC
        """
    )
    return [dict(r) for r in rows]


# ---------------------------------------------------------------------------
#  Chrome (shared header/footer, taken from a reference page)
# ---------------------------------------------------------------------------
def split_chrome(shell: str) -> dict:
    i_title = shell.index("<title>")
    i_links = _line_start(shell, shell.index('<link rel="preconnect"'))
    i_ld = _line_start(shell, shell.index('<script type="application/ld+json">'))
    i_head_end = shell.index("</head>")
    i_main = shell.index('<main id="main-content"')
    i_main_tag_end = shell.index(">", i_main) + 1
    i_after_main = shell.index("</main>")

    body_prefix = shell[i_head_end:i_main_tag_end].replace(' aria-current="page"', "")
    return {
        "head_prefix": shell[:i_title],
        "head_links": shell[i_links:i_ld],
        "body_prefix": body_prefix,
        "body_suffix": shell[i_after_main:],
    }


def render_page(article: dict, articles: list[dict], chrome: dict) -> str:
    url = f"{SITE_URL}/{article['slug']}.html"
    title = _text(article.get("meta_title")) or _text(article["title"])
    if "amin sharif" not in title.lower():
        title = f"{title} | Amin Sharif"
    description = _text(article.get("meta_description")) or _text(article["excerpt"])
    image = _abs(article.get("cover_image"))
    published = article.get("published_at")
    modified = article.get("updated_at") or published
    category = None
    if article.get("category_slug"):
        category = {"name": _text(article["category_name"]), "slug": article["category_slug"]}

    related = []
    for other in articles:
        if other["slug"] == article["slug"]:
            continue
        if len(related) == 3:
            break
        related.append(
            {
                "href": article_href(other),
                "category": _text(other.get("category_name")) or "Insights",
                "title": _text(other["title"]),
                "excerpt": _text(other.get("excerpt")),
                "read_time": other.get("read_time") or 5,
            }
        )

    main = _env.get_template(TEMPLATE).render(
        crumb=_text(article["title"]),
        category=category,
        title=_text(article["title"]),
        date_display=_pretty_day(published),
        read_time=article.get("read_time") or 5,
        excerpt=_text(article.get("excerpt")),
        content=article.get("content") or "<p>This article has no content yet.</p>",
        related=related,
    )

    meta = (
        f"<title>{_attr(title)}</title>\n"
        f'  <meta name="description" content="{_attr(description)}">\n'
        '  <meta name="author" content="Amin Sharif">\n'
        '  <meta name="robots" content="index, follow, max-image-preview:large">\n'
        '  <meta name="theme-color" content="#ffffff">\n'
        f'  <link rel="canonical" href="{url}">\n'
        "\n"
        '  <meta property="og:type" content="article">\n'
        '  <meta property="og:site_name" content="Amin Sharif — AI Automation Agency">\n'
        '  <meta property="og:locale" content="en_US">\n'
        f'  <meta property="og:url" content="{url}">\n'
        f'  <meta property="og:title" content="{_attr(title)}">\n'
        f'  <meta property="og:description" content="{_attr(description)}">\n'
        f'  <meta property="og:image" content="{_abs(article.get("cover_image"))}">\n'
        '  <meta property="article:published_time" content="'
        + _iso_day(published)
        + '">\n'
        '  <meta name="twitter:card" content="summary_large_image">\n'
        f'  <meta name="twitter:title" content="{_attr(title)}">\n'
        f'  <meta name="twitter:description" content="{_attr(description)}">\n'
        f'  <meta name="twitter:image" content="{image}">\n'
        "\n"
    )

    graph = [
        {
            "@type": "Person",
            "@id": SITE_URL + "/#founder",
            "name": "Amin Sharif",
            "url": SITE_URL + "/about.html",
            "jobTitle": "AI Automation Developer",
        },
        {
            "@type": "Organization",
            "@id": SITE_URL + "/#organization",
            "name": "Amin Sharif",
            "url": SITE_URL + "/",
            "sameAs": ["https://github.com/Aminsharif"],
        },
        {
            "@type": "BlogPosting",
            "@id": url + "#article",
            "headline": _text(article["title"]),
            "description": description,
            "datePublished": _iso_day(published),
            "dateModified": _iso_day(modified),
            "author": {"@id": SITE_URL + "/#founder"},
            "publisher": {"@id": SITE_URL + "/#organization"},
            "mainEntityOfPage": {"@type": "WebPage", "@id": url},
            "inLanguage": "en",
            "articleSection": category["name"] if category else "Insights",
        },
        {
            "@type": "BreadcrumbList",
            "@id": url + "#breadcrumb",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE_URL + "/"},
                {"@type": "ListItem", "position": 2, "name": "Insights", "item": SITE_URL + "/insights.html"},
                {"@type": "ListItem", "position": 3, "name": _text(article["title"]), "item": url},
            ],
        },
    ]
    ld_json = json.dumps({"@context": "https://schema.org", "@graph": graph}, indent=2, ensure_ascii=False)
    ld_block = '  <script type="application/ld+json">\n' + "\n".join(
        "  " + line for line in ld_json.splitlines()
    ) + "\n  </script>\n"

    return (
        GENERATED_MARKER
        + "\n"
        + chrome["head_prefix"]
        + meta
        + chrome["head_links"]
        + ld_block
        + chrome["body_prefix"]
        + "\n\n"
        + main
        + "\n  "
        + chrome["body_suffix"]
    )


# ---------------------------------------------------------------------------
#  Sitemap
# ---------------------------------------------------------------------------
def render_sitemap(articles: list[dict]) -> str:
    def entry(loc: str, lastmod: str, changefreq: str, priority: str) -> str:
        return (
            "  <url>\n"
            f"    <loc>{loc}</loc>\n"
            f"    <lastmod>{lastmod}</lastmod>\n"
            f"    <changefreq>{changefreq}</changefreq>\n"
            f"    <priority>{priority}</priority>\n"
            "  </url>\n"
        )

    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for filename, loc, changefreq, priority in STATIC_PAGES:
        path = ROOT_DIR / filename
        stamp = date.fromtimestamp(path.stat().st_mtime).isoformat() if path.is_file() else date.today().isoformat()
        lines.append(entry(SITE_URL + "/" + loc, stamp, changefreq, priority).rstrip("\n"))
        if filename == INSIGHTS_PAGE:
            for article in articles:
                lines.append(
                    entry(
                        SITE_URL + "/" + article_href(article),
                        _iso_day(article.get("updated_at") or article.get("published_at")),
                        ARTICLE_CHANGEFREQ,
                        ARTICLE_PRIORITY,
                    ).rstrip("\n")
                )
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
#  Insights <noscript> fallback list
# ---------------------------------------------------------------------------
def render_noscript(articles: list[dict]) -> str:
    cards = []
    for article in articles:
        category = _text(article.get("category_name")) or "Insights"
        cards.append(
            '              <a class="kf-card" href="'
            + _attr(article_href(article))
            + '"><article>\n'
            '                <span class="kf-eyebrow kf-card__cat">' + html.escape(category) + "</span>\n"
            '                <h3 class="kf-card__title">' + html.escape(_text(article["title"])) + "</h3>\n"
            '                <p class="kf-card__excerpt">' + html.escape(_text(article.get("excerpt"))) + "</p>\n"
            '                <div class="kf-meta"><span>' + html.escape(str(article.get("read_time") or 5)) + " min read</span></div>\n"
            "              </article></a>"
        )
    return "\n".join(cards)


def patch_noscript(page: str, articles: list[dict]) -> str:
    start = page.index(NOSCRIPT_START) + len(NOSCRIPT_START)
    end = page.index(NOSCRIPT_END)
    return page[:start] + "\n" + render_noscript(articles) + "\n              " + page[end:]


# ---------------------------------------------------------------------------
#  Insights Blog JSON-LD article list
# ---------------------------------------------------------------------------
def render_blogposts(articles: list[dict]) -> str:
    lines = []
    for index, article in enumerate(articles):
        comma = "," if index < len(articles) - 1 else ""
        lines.append(
            BLOGPOST_INDENT
            + '{ "@type": "BlogPosting", "headline": '
            + json.dumps(_text(article["title"]), ensure_ascii=False)
            + ', "url": "'
            + SITE_URL
            + "/"
            + article_href(article)
            + '" }'
            + comma
        )
    return "\n".join(lines)


def patch_blogposts(page: str, articles: list[dict]) -> str:
    start = page.find(BLOGPOST_OPEN)
    if start == -1:
        raise RuntimeError(f"insights.html is missing the {BLOGPOST_OPEN} JSON-LD list")
    start += len(BLOGPOST_OPEN)
    end = page.find(BLOGPOST_CLOSE, start)
    if end == -1:
        raise RuntimeError("insights.html JSON-LD blogPost list is not terminated")
    return page[:start] + "\n" + render_blogposts(articles) + page[end:]


def unlisted_pages(articles: list[dict]) -> list[str]:
    """Indexable root pages that are missing from sitemap.xml.

    A new hand-written page is easy to add and easy to forget to list, which
    hides it from search engines. This turns that silence into a warning.
    """
    listed = {page[0] for page in STATIC_PAGES}
    owned = {article_href(article) for article in articles}
    unlisted = []
    for path in sorted(ROOT_DIR.glob("*.html")):
        if path.name in listed or path.name in owned or is_generated(path):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "noindex" in text.lower():
            continue
        unlisted.append(path.name)
    return unlisted


# ---------------------------------------------------------------------------
#  Build
# ---------------------------------------------------------------------------
def plan_pages() -> tuple[dict[str, str], list[dict]]:
    """Render every generated page.

    Returns ``({relative path: expected content}, published articles)``.
    """
    chrome = split_chrome((ROOT_DIR / CHROME_SOURCE).read_text(encoding="utf-8"))
    articles = load_articles()

    outputs: dict[str, str] = {}
    for article in articles:
        target = build_target(article)
        if target is None:
            continue  # hand-written page or hosted elsewhere: leave it alone
        outputs[target] = render_page(article, articles, chrome)

    outputs[INSIGHTS_PAGE] = patch_blogposts(
        patch_noscript(
            (ROOT_DIR / INSIGHTS_PAGE).read_text(encoding="utf-8"), articles
        ),
        articles,
    )
    return outputs, articles


def orphaned_generated(articles: list[dict]) -> list[Path]:
    keep = {article_href(a) for a in articles}
    found = []
    for path in ROOT_DIR.glob("*.html"):
        if path.name in keep or path.name in {p[0] for p in STATIC_PAGES}:
            continue
        if is_generated(path):
            found.append(path)
    return found


def run(check: bool) -> int:
    outputs, articles = plan_pages()
    problems: list[str] = []

    def sync(relative: str, content: str) -> None:
        path = ROOT_DIR / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            return
        if check:
            problems.append(relative)
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="")
        print(f"  wrote   {relative}")

    for relative, content in sorted(outputs.items()):
        sync(relative, content)

    # sitemap.xml records each page's file mtime, so it has to be rendered
    # after the pages above have been written.
    sync(SITEMAP, render_sitemap(articles))

    # Indexable pages that nobody listed in STATIC_PAGES are invisible to
    # search engines — say so loudly instead of shipping a silent omission.
    unlisted = unlisted_pages(articles)
    if unlisted:
        print(
            "\nWarning: indexable pages missing from sitemap.xml - add them to "
            "STATIC_PAGES in backend/build.py:",
            file=sys.stderr,
        )
        for name in unlisted:
            print(f"  - {name}", file=sys.stderr)
        if check:
            problems.extend(f"{name} (missing from sitemap)" for name in unlisted)

    if check:
        for path in orphaned_generated(articles):
            problems.append(path.name + " (orphaned)")
    else:
        # Keep the database in sync so the API links to the static files.
        for article in articles:
            target = article_href(article)
            if (article.get("external_url") or "") != target:
                execute(
                    "UPDATE articles SET external_url = %s WHERE id = %s",
                    (target, article["id"]),
                )
                print(f"  linked  {article['slug']} -> {target}")

        for path in orphaned_generated(articles):
            path.unlink()
            print(f"  removed {path.name}")

    if problems:
        print("\nOut of date (run: python -m backend.build):", file=sys.stderr)
        for name in problems:
            print(f"  - {name}", file=sys.stderr)
        return 1

    if check:
        print("Static articles, sitemap and insights fallback are up to date.")
    else:
        print("Done.")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="backend.build", description="Generate static article pages")
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args(argv)
    try:
        return run(args.check)
    finally:
        close_pool()


if __name__ == "__main__":
    raise SystemExit(main())
